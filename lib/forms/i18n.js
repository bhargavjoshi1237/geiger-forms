const DICTIONARIES = { en, es, fr, de, pt, hi, ar };

export function resolveLocale(locale) {
  const base = String(locale || "en").toLowerCase().split(/[-_]/)[0];
  return DICTIONARIES[base] ? base : "en";
}

export function isRtl(locale) {
  return resolveLocale(locale) === "ar";
}

// Translates a chrome key, interpolating {vars}; unknown keys fall back to English, then the key itself.
export function t(locale, key, vars) {
  const dict = DICTIONARIES[resolveLocale(locale)];
  const template = dict[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

// Curried translator bound to one locale.
export function translator(locale) {
  return (key, vars) => t(locale, key, vars);
}

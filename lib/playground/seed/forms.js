function field(id, type, title, extra = {}) {
  return {
    id,
    type,
    title,
    label: title,
    placeholder: "",
    hint: "",
    info: "",
    required: false,
    options: [],
    formula: "",
    conditions: [],
    conditionLogic: "all",
    included: true,
    width: "full",
    readOnly: false,
    sensitive: false,
    ...extra,
  };
}

